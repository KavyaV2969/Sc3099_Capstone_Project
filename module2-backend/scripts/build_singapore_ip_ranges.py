"""Build app/data/singapore_ip_ranges.txt from an APNIC delegated statistics file.

Usage (download first, then pass the local path; nothing is fetched here):
    curl -O https://ftp.apnic.net/stats/apnic/delegated-apnic-latest
    curl -O https://ftp.apnic.net/stats/apnic/delegated-apnic-latest.md5
    python -m scripts.build_singapore_ip_ranges delegated-apnic-latest

Only allocated/assigned SG records are used. Adjacent blocks are merged into CIDRs.
"""
import hashlib
import sys
from datetime import date
from ipaddress import IPv4Address, collapse_addresses, ip_network, summarize_address_range
from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "app" / "data" / "singapore_ip_ranges.txt"
SOURCE = "https://ftp.apnic.net/stats/apnic/delegated-apnic-latest"


def parse(path: Path):
    serial, networks = None, {4: [], 6: []}
    for line in path.read_text(encoding="ascii").splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("|")
        if fields[0] == "2" and serial is None:  # Version line: 2|apnic|serial|records|start|end|utc
            serial = fields[2]
            continue
        if len(fields) < 7 or fields[1] != "SG" or fields[6] not in {"allocated", "assigned"}:
            continue
        kind, start, value = fields[2], fields[3], int(fields[4])
        if kind == "ipv4":  # IPv4 value is an address count, not always a power of two.
            first = IPv4Address(start)
            networks[4].extend(summarize_address_range(first, first + value - 1))
        elif kind == "ipv6":  # IPv6 value is a prefix length.
            networks[6].append(ip_network(f"{start}/{value}"))
    if serial is None:
        raise ValueError("not an APNIC delegated statistics file (missing version line)")
    return serial, [list(collapse_addresses(networks[v])) for v in (4, 6)]


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    path = Path(argv[1])
    md5 = hashlib.md5(path.read_bytes()).hexdigest()
    serial, (ipv4, ipv6) = parse(path)
    header = [
        "# Singapore (SG) IP address blocks from APNIC delegated statistics.",
        f"# Source: {SOURCE}",
        f"# APNIC serial: {serial}; source MD5: {md5}; generated {date.today().isoformat()}",
        "# Generated by scripts/build_singapore_ip_ranges.py; allocated/assigned records, merged.",
        "# Registry country of first allocation, not live geolocation (see APNIC conditions of use).",
        f"# {len(ipv4)} IPv4 and {len(ipv6)} IPv6 networks.",
    ]
    lines = header + [str(n) for n in ipv4] + [str(n) for n in ipv6]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"Wrote {OUTPUT} ({len(ipv4)} IPv4, {len(ipv6)} IPv6 networks; serial {serial})")


if __name__ == "__main__":
    main(sys.argv)
